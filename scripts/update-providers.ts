// Refreshes the bundled provider catalog from models.dev (MIT), so a `provider:` model prefix needs no base URL.
// Keeps the OpenAI-compatible providers that list a base URL. Run before a release:
//   node scripts/update-providers.ts
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const RESERVED = new Set(['claude', 'anthropic-api', 'codex', 'antigravity', 'grok', 'custom']);
const response = await fetch('https://models.dev/api.json');
if (!response.ok) throw new Error(`models.dev: ${response.status}`);
const all = (await response.json()) as Record<string, { name?: string; api?: string; npm?: string; env?: string[] }>;
const kept = Object.entries(all)
  .filter(([id, p]) => p.npm === '@ai-sdk/openai-compatible' && p.api && /^https?:\/\//.test(p.api) && !RESERVED.has(id) && /^[a-z0-9][a-z0-9.-]*$/.test(id))
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([id, p]) => `  ${JSON.stringify(id)}: { name: ${JSON.stringify(p.name ?? id)}, baseUrl: ${JSON.stringify(p.api!.replace(/\/$/, ''))}, env: ${JSON.stringify(p.env ?? [])} },`);
const out = `// GENERATED by scripts/update-providers.ts on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
// Source: https://models.dev (catalog of AI providers), MIT License, Copyright (c) 2025 models.dev.
// The OpenAI-compatible providers that list a base URL: a model name "id:model" resolves its base URL here.
// env lists the provider's usual key variable, for reference only: keys are always passed explicitly.

export interface CatalogProvider { name: string; baseUrl: string; env: string[] }

export const CATALOG_PROVIDERS: Record<string, CatalogProvider> = {
${kept.join('\n')}
};
`;
const target = fileURLToPath(new URL('../src/models/providers.generated.ts', import.meta.url));
writeFileSync(target, out);
console.log(`wrote ${kept.length} providers to ${target}`);
